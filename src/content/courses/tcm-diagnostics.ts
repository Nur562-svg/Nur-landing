function createDemoKnowledgePoint(
  id: string,
  slug: string,
  order: number,
  title: string,
  note: string,
  emphasis: KnowledgeEmphasis,
  options: DemoKnowledgePointOptions = {},
): KnowledgePointDefinition {
  return {
    id,
    slug,
    order,
    title,
    note,
    emphasis,
    contentStatus: options.contentStatus ?? "demo",
    evidenceFramework: options.evidenceFramework ?? [],
    lenses: options.lenses ?? [],
    relationships: options.relationships ?? [],
    learningMemoryCriteria: options.learningMemoryCriteria ?? [],
    sourceIds: options.sourceIds ?? [],
    learningTaskIds: [],
    assessmentItemIds: options.assessmentItemIds ?? [],
    caseIds: options.caseIds ?? [],
    lesson: options.lesson ?? null,
  };
}

